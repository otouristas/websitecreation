/**
 * Regional «κατασκευή ιστοσελίδων» pages under /el/kataskevi-istoselidon.
 *
 * Why these exist: «κατασκευή ιστοσελίδων κρήτη» has about 100 searches a
 * month in Greece (Ahrefs, 2026-11) and the SERP is filled with Heraklion
 * agencies. Nothing on the site answered the region query: the city pages
 * (heraklion-gr, chania-gr, rethymno-gr, santorini-gr...) own the city
 * phrases, and crete-gr was dropped from the service × city grid. The region
 * pages own the region phrase only and send the reader to the city page that
 * matches. They never repeat a city page's copy.
 *
 * Greek only. No address, rating or invented results.
 */

export interface WebsiteRegionSection {
  readonly heading: string;
  readonly paragraphs: readonly string[];
}

export interface WebsiteRegionFaq {
  readonly question: string;
  readonly answer: string;
}

export interface WebsiteRegionLink {
  readonly label: string;
  readonly href: string;
  readonly body: string;
}

export interface WebsiteRegionPage {
  /** URL segment: /el/kataskevi-istoselidon/<slug> */
  readonly slug: string;
  /** Nominative: «Κρήτη». */
  readonly name: string;
  /** Locative: «στην Κρήτη». */
  readonly locative: string;
  /** The one phrase this URL owns. */
  readonly primaryKeyword: string;
  readonly title: string;
  readonly description: string;
  readonly h1: string;
  readonly h1Accent: string;
  readonly lead: string;
  readonly sections: readonly WebsiteRegionSection[];
  /** City pages for the same service. These own the city phrases. */
  readonly cities: readonly WebsiteRegionLink[];
  readonly faqs: readonly WebsiteRegionFaq[];
  /** The matching /el/seo place page. */
  readonly seoPlace: { readonly label: string; readonly href: string };
  readonly workSlugs: readonly string[];
}

