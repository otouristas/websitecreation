export function getWebsiteRegion(slug: string): WebsiteRegionPage | undefined {
  return WEBSITE_REGION_PAGES.find((page) => page.slug === slug);
}

export function websiteRegionPath(slug: string): string {
  return `/el/kataskevi-istoselidon/${slug}`;
}

/** City slugs (service × city grid) that sit inside a regional page. */
const REGION_BY_CITY: Readonly<Record<string, string>> = {
  'heraklion-gr': 'kriti',
  'chania-gr': 'kriti',
  'rethymno-gr': 'kriti',
  'santorini-gr': 'kyklades',
  'mykonos-gr': 'kyklades',
  'paros-gr': 'kyklades',
  'naxos-gr': 'kyklades',
};

/** The regional page a Greek website-creation city page links up to, if any. */
export function websiteRegionForCity(citySlug: string): { label: string; href: string } | undefined {
  const page = getWebsiteRegion(REGION_BY_CITY[citySlug] ?? '');
  if (!page) return undefined;
  return { label: `Όλη η ${page.name}`.replace('Όλη η Κυκλάδες', 'Όλες οι Κυκλάδες'), href: websiteRegionPath(page.slug) };
}
