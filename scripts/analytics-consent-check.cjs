const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const ts = require('typescript');
const source = ts.transpileModule(fs.readFileSync('src/lib/analytics.ts', 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText;
let consent = null;
const scripts = [];
const window = {location: {origin: 'https://anotherseoguru.com', pathname: '/en/contact', href: 'https://anotherseoguru.com/en/contact?email=private@example.com'}};
const document = {title: 'Contact', cookie: '', getElementById: id => scripts.find(s => s.id === id), createElement: () => ({}), head: {appendChild: el => scripts.push(el)}};
const context = {window, document, localStorage: {getItem: key => key === 'cookie-consent' ? consent : null}, exports: {}, URL, URLSearchParams, Date};
vm.runInNewContext(source, context);
const api = context.exports;
api.loadGoogleAnalytics();
assert.equal(scripts.length, 0, 'No tag without consent');
consent = 'accepted'; api.enableGoogleAnalytics();
assert.equal(scripts.length, 1);
const commands = () => window.dataLayer.map(args => Array.from(args));
const pageView = commands().find(a => a[0] === 'event' && a[1] === 'page_view');
assert.equal(pageView[2].page_location, 'https://anotherseoguru.com/en/contact');
assert.equal(pageView[2].page_referrer, '');
assert.ok(!JSON.stringify(commands()).includes('private@example.com'));
consent = 'declined'; api.disableGoogleAnalytics();
const count = window.dataLayer.length;
api.trackLead('contact');
assert.equal(window.dataLayer.length, count, 'Revoked consent blocks lead events');
assert.equal(window['ga-disable-G-FGFJEKZHB1'], true);
consent = 'accepted'; api.enableGoogleAnalytics();
assert.equal(scripts.length, 1, 'Reaccepting does not duplicate the tag');
assert.equal(window['ga-disable-G-FGFJEKZHB1'], false);
assert.equal(commands().filter(a => a[0] === 'consent' && a[1] === 'update' && a[2].analytics_storage).at(-1)[2].analytics_storage, 'granted');
console.log('PASS: default-off, query redaction, revocation, reacceptance and single tag');
